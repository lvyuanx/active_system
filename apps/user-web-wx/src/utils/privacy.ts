export type LegalDocumentType = "service" | "privacy";

export interface LegalSection {
  title: string;
  paragraphs: string[];
  items?: string[];
}

export interface LegalDocument {
  title: string;
  subtitle: string;
  updatedAt: string;
  sections: LegalSection[];
}

export const userAgreementVersion = "2026-10-09";

const agreementStorageKey = "active_user_agreement";

export const isAgreementVersionAccepted = (
  value: unknown,
  version = userAgreementVersion,
) => Boolean(
  value
  && typeof value === "object"
  && (value as { version?: unknown }).version === version,
);

export const isUserAgreementAccepted = () => {
  const value = wx.getStorageSync(agreementStorageKey);
  return isAgreementVersionAccepted(value);
};

export const acceptUserAgreement = () => {
  wx.setStorageSync(agreementStorageKey, {
    version: userAgreementVersion,
    accepted_at: new Date().toISOString(),
  });
};

export const revokeUserAgreement = () => {
  wx.removeStorageSync(agreementStorageKey);
};

export const requestWechatPrivacyAuthorize = () => new Promise<boolean>((resolve) => {
  if (typeof wx.requirePrivacyAuthorize !== "function") {
    resolve(true);
    return;
  }
  try {
    wx.requirePrivacyAuthorize({
      success: () => resolve(true),
      fail: () => resolve(false),
    });
  } catch {
    resolve(false);
  }
});

export const openLegalDocument = (type: LegalDocumentType) => {
  wx.navigateTo({ url: `/pages/legal/index?type=${type}` });
};

